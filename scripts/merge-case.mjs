#!/usr/bin/env node
// Merges case/parts/*.yaml fragments into case/main.yaml.
// Fragments are owned by different authors; merge is by id for lists of
// objects, deep for mappings, concat+dedupe for scalars and canonical_qa.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parse, stringify } from 'yaml';

const PARTS_DIR = resolve('case/parts');
const OUT_PATH = resolve('case/main.yaml');

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const idOf = (v) => (isObj(v) && typeof v.id === 'string' ? v.id : null);

function merge(a, b, path = '') {
  if (b === undefined) return a;
  if (a === undefined) return b;
  if (Array.isArray(a) && Array.isArray(b)) {
    const keyed = a.some(idOf) || b.some(idOf);
    if (!keyed) {
      const out = [...a];
      for (const item of b) {
        if (!out.some((x) => JSON.stringify(x) === JSON.stringify(item))) out.push(item);
      }
      return out;
    }
    const out = [...a];
    for (const item of b) {
      const id = idOf(item);
      const idx = id ? out.findIndex((x) => idOf(x) === id) : -1;
      if (idx === -1) out.push(item);
      else out[idx] = merge(out[idx], item, `${path}/${id}`);
    }
    return out;
  }
  if (isObj(a) && isObj(b)) {
    const out = { ...a };
    for (const k of Object.keys(b)) out[k] = merge(a[k], b[k], `${path}/${k}`);
    return out;
  }
  return b;
}

const files = readdirSync(PARTS_DIR)
  .filter((f) => f.endsWith('.yaml') || f.endsWith('.yml'))
  .sort();

if (!files.length) {
  console.error('FAIL  no case fragments in case/parts/');
  process.exit(1);
}

let merged = null;
for (const file of files) {
  const data = parse(readFileSync(join(PARTS_DIR, file), 'utf8'));
  if (!isObj(data)) {
    console.error(`FAIL  ${file}: fragment must be a YAML mapping`);
    process.exit(1);
  }
  merged = merged ? merge(merged, data, file) : data;
  console.log(`  merge ${file}`);
}

const banner = '# generated by scripts/merge-case.mjs from case/parts/*.yaml — edit the fragments, not this file\n';
writeFileSync(OUT_PATH, banner + stringify(merged, { lineWidth: 0 }), 'utf8');
console.log(`OK    merged ${files.length} fragment(s) -> ${OUT_PATH}`);
