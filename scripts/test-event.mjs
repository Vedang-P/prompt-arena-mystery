import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const directory=await fs.mkdtemp(path.join(os.tmpdir(),'arena-event-'));
process.env.SQLITE_PATH=path.join(directory,'event.db');
process.env.EVENT_MODE='true';
const {default:app}=await import('../src/worker.js');
const {getEnv}=await import('../lib/vercel-env.js');const env=await getEnv();
const request=(url,cookie,body)=>app.fetch(new Request('http://localhost'+url,{method:body?'POST':'GET',headers:{...(cookie?{cookie}:{}),...(body?{'content-type':'application/json'}:{})},body:body?JSON.stringify(body):undefined}),env);
const start=performance.now();
// Event play no longer needs pre-issued codes: every guest picks a username at the door.
const teams=await Promise.all(Array.from({length:70},async(_,i)=>{
  const name=`Event team ${i+1}`;
  const login=await request('/api/guest',null,{username:name});assert.equal(login.status,200);
  const cookie=login.headers.get('set-cookie').split(';')[0];
  const state=await(await request('/api/state',cookie)).json();assert.equal(state.team,name);assert.equal(state.act,'act0');
  return {cookie,state};
}));
assert.equal((await request('/api/guest',null,{username:'Walk-in guest'})).status,200,'guest sign-in stays open in event mode');
assert.equal((await request('/api/practice',teams[0].cookie,{act:'act8'})).status,403);
assert.equal((await request('/api/accuse',teams[0].cookie,{culprit:'sameer'})).status,403);
let leaderboard=await(await request('/api/leaderboard')).json();assert.equal(leaderboard.teams.length,71,'the walk-in joins the 70 pre-signed teams');assert(leaderboard.teams.every(t=>t.elapsedSeconds===0));
await Promise.all(teams.map(async t=>{const r=await request('/api/act/complete',t.cookie,{act:'act0'});assert.equal(r.status,200);}));
const first=await env.DB.prepare('SELECT started_at FROM progress WHERE team_id = ?').bind(1).first();
await new Promise(r=>setTimeout(r,1200));
await request('/api/act/complete',teams[0].cookie,{act:'act0'});
const again=await env.DB.prepare('SELECT started_at FROM progress WHERE team_id = ?').bind(1).first();assert.equal(first.started_at,again.started_at);
leaderboard=await(await request('/api/leaderboard')).json();
assert.equal(leaderboard.teams.filter(t=>t.act==='act1').length,70,'every completing team advances to Act 1');
assert(leaderboard.teams.some(t=>t.act==='act0'&&t.name==='Walk-in guest'),'the walk-in is still on the board at the prologue');
assert(leaderboard.teams.every(t=>t.act!=='act0'||t.name==='Walk-in guest'));
assert(leaderboard.teams.filter(t=>t.act==='act1').every(t=>t.elapsedSeconds>=1));
assert(!JSON.stringify(leaderboard).includes('code_hash'));
await Promise.all(teams.map(async t=>{const r=await request('/api/act/complete',t.cookie,{act:'act8'});assert.equal(r.status,409);}));
console.log(`PASS 70 simultaneous team sessions, isolated saves, Act 1 timing, timer persistence, leaderboard, event entry restrictions and future-act gates (${Math.round(performance.now()-start)} ms).`);
process.exit(0);
